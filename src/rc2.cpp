Rc2::Rc2(const QByteArray &key)
{
    const int t = qBound(1, static_cast<int>(key.size()), 128);

    // расширение ключа до 128 байт
    uint8_t l[128] = {};
    memcpy(l, key.constData(), t);
    for (int i = t; i < 128; ++i)
        l[i] = kPiTable[(l[i - 1] + l[i - t]) & 0xff];
    // эффективная длина равна фактической (8*t бит), поэтому маска равна 0xff
    l[128 - t] = kPiTable[l[128 - t]];
    for (int i = 127 - t; i >= 0; --i)
        l[i] = kPiTable[l[i + 1] ^ l[i + t]];

    for (int i = 0; i < 64; ++i)
        m_k[i] = static_cast<uint16_t>(l[2 * i] | (l[2 * i + 1] << 8));
    memset(l, 0, sizeof(l));
}

Rc2::~Rc2()
{
    // ключевой материал не должен оставаться в памяти после использования
    volatile unsigned short *p = m_k;
    for (int i = 0; i < 64; ++i)
        p[i] = 0;
}

void Rc2::encryptBlock(const unsigned char in[BlockSize], unsigned char out[BlockSize]) const
{
    static const int kShift[4] = { 1, 2, 3, 5 };

    uint16_t r[4];
    for (int i = 0; i < 4; ++i)
        r[i] = static_cast<uint16_t>(in[2 * i] | (in[2 * i + 1] << 8));

    int j = 0;
    auto mix = [&]() {
        for (int i = 0; i < 4; ++i) {
            r[i] = static_cast<uint16_t>(r[i] + m_k[j++]
                                         + (r[(i + 3) & 3] & r[(i + 2) & 3])
                                         + (~r[(i + 3) & 3] & r[(i + 1) & 3]));
            r[i] = rol16(r[i], kShift[i]);
        }
    };
    auto mash = [&]() {
        for (int i = 0; i < 4; ++i)
            r[i] = static_cast<uint16_t>(r[i] + m_k[r[(i + 3) & 3] & 63]);
    };

    for (int n = 0; n < 5; ++n) mix();
    mash();
    for (int n = 0; n < 6; ++n) mix();
    mash();
    for (int n = 0; n < 5; ++n) mix();

    for (int i = 0; i < 4; ++i) {
        out[2 * i] = static_cast<unsigned char>(r[i] & 0xff);
        out[2 * i + 1] = static_cast<unsigned char>(r[i] >> 8);
    }
}

QByteArray rc2Cfb(const Rc2 &cipher, const QByteArray &data, bool decrypt)
{
    unsigned char reg[Rc2::BlockSize] = {}; // сдвиговый регистр, начальный вектор нулевой
    unsigned char gamma[Rc2::BlockSize];

    QByteArray result(data.size(), Qt::Uninitialized);
    for (int i = 0; i < data.size(); ++i) {
        cipher.encryptBlock(reg, gamma);

        const unsigned char in = static_cast<unsigned char>(data[i]);
        const unsigned char out = in ^ gamma[0];
        result[i] = static_cast<char>(out);

        // в регистр возвращается байт шифротекста
        memmove(reg, reg + 1, Rc2::BlockSize - 1);
        reg[Rc2::BlockSize - 1] = decrypt ? in : out;
    }
    return result;
}
